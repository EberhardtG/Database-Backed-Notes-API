"""
WHY:
The NoteResponse schema defines the structure of note objects returned by the
API. It ensures that all outgoing data is consistent with the SQLAlchemy Note
model and provides a clean, predictable format for clients consuming the API.
Using from_attributes=True allows Pydantic to serialize SQLAlchemy ORM objects
directly without requiring manual conversion.

DESIGN:
1. The id field is required and reflects the primary key generated by the
   database. This ensures that every returned note can be uniquely identified.

2. The title and content fields mirror the validation rules used during note
   creation, guaranteeing that response data remains consistent with input
   constraints.

3. The category field is optional and capped at 50 characters, matching the
   database column definition and preventing overly long category labels.

4. The is_pinned field defaults to False and indicates whether a note has been
   marked for priority display.

5. The created_at field is required because the database automatically generates
   it when the note is created. Including it in the response allows clients to
   track when notes were added.

6. The model_config uses from_attributes=True, enabling Pydantic to read fields
   directly from SQLAlchemy model instances. This eliminates the need for manual
   dict conversion and ensures seamless ORM integration.

Overall, this schema provides a clean, validated, and database‑aligned structure
for all note responses, ensuring consistency and reliability across the API.
"""


from pydantic import BaseModel, ConfigDict, Field
from typing import Optional
from datetime import datetime



class NoteResponse(BaseModel):
    id:int
    title :str = Field(min_length=1, max_length=200)
    content:str = Field(min_length=1)
    category: Optional[str]=Field(default=None, max_length=50)
    is_pinned: bool =Field(default=False)
    created_at:datetime

    model_config = ConfigDict(from_attributes=True)